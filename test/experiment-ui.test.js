import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {browserHarness,pointer} from '../test-support/browser.js';
const EXP='hexhaven-experiment-v07',NORMAL='hexhaven-save-v3';
test('experiment UI changes difficulty, restarts, copies metrics and preserves ordinary progress',async()=>{
 const legacy=JSON.parse(readFileSync(new URL('./fixtures/main-v3-save.json',import.meta.url)));
 const {element,storage,listeners,html}=browserHarness([[NORMAL,JSON.stringify(legacy)]]);
 await import('../src/main.js');
 let current=JSON.parse(storage.get(EXP));assert.equal(current.experiment.difficulty,'standard');
 assert.equal(current.deck.length,18);assert.equal(element('difficulty').disabled,false);
 assert.equal(element('tilegrab').handlers.has('pointerdown'),false);assert.ok(!html.includes('dragpreview'));
 const board=element('board');
 board.handlers.get('pointerdown')(pointer(259,422));board.handlers.get('pointerup')(pointer(259,422));
 element('right').onclick();element('confirm').onclick();element('undo').onclick();
 assert.equal(JSON.parse(storage.get(EXP)).metrics.undos,1);
 element('restart').onclick();current=JSON.parse(storage.get(EXP));
 assert.equal(current.metrics.restarts,1);assert.equal(current.metrics.undos,1);
 element('test-toggle').onclick();assert.equal(element('test-panel').hidden,false);
 const report=JSON.parse(element('test-result').value);assert.equal(report.usedTiles,0);assert.equal(report.restarts,1);
 const originalNavigator=Object.getOwnPropertyDescriptor(globalThis,'navigator');
 let copied='';Object.defineProperty(globalThis,'navigator',{configurable:true,value:{clipboard:{writeText:async value=>{copied=value;}}}});
 await element('copy-result').onclick();assert.equal(copied,element('test-result').value);
 Object.defineProperty(globalThis,'navigator',{configurable:true,value:{}});
 await element('copy-result').onclick();assert.equal(element('test-result').selected,true);
 if(originalNavigator)Object.defineProperty(globalThis,'navigator',originalNavigator);else delete globalThis.navigator;
 element('seed').value='42';element('difficulty').value='challenge';element('difficulty').onchange();
 current=JSON.parse(storage.get(EXP));assert.equal(current.experiment.difficulty,'challenge');assert.equal(current.experiment.seed,42);
 assert.equal(current.index,0);assert.deepEqual(current.metrics,{restarts:0,undos:0});
 const experimental=storage.get(EXP);
 listeners.get('keydown')({key:'ArrowLeft',target:{tagName:'INPUT'}});assert.equal(storage.get(EXP),experimental);
 element('seed').value='no';element('new-experiment').onclick();assert.equal(storage.get(EXP),experimental);
 element('switch-view').onclick();assert.deepEqual(JSON.parse(storage.get(NORMAL)),legacy);
 assert.equal(element('difficulty').disabled,true);assert.equal(element('test-panel').hidden,true);
 assert.equal(storage.get(EXP),experimental);
 element('switch-view').onclick();assert.equal(storage.get(EXP),experimental);
 assert.equal(element('seed').value,42);assert.equal(listeners.has('pointermove'),false);
});
test('saved experiment resumes and discovery UI is not replayed on load',async()=>{
 const {createExperiment,serialize}=await import('../src/engine.js');
 const game=createExperiment('comfort',1);game.ecosystem.seen=['river'];game.metrics={restarts:2,undos:3};
 const {element,storage,timers}=browserHarness([[EXP,JSON.stringify(serialize(game))]]);
 await import('../src/main.js?resume');
 assert.deepEqual(JSON.parse(storage.get(EXP)),serialize(game));
 assert.equal(element('discovery').hidden,true);assert.equal(timers.size,0);
});

test('discovery messages show causes in order, are cancelled by undo and do not repeat on replay',async()=>{
 const {createExperiment,serialize}=await import('../src/engine.js');
 const game=createExperiment('comfort',7),edges=terrain=>Array(6).fill(terrain);
 game.board=new Map();
 for(let q=0;q<3;q++)game.board.set(`${q},0`,{q,r:0,edges:edges('water'),id:'water'+q});
 game.board.set('0,1',{q:0,r:1,edges:edges('forest'),id:'bank'});
 game.deck=[{id:'new-bank',edges:edges('forest')}];game.target=999;
 const {element,storage,timers}=browserHarness([[EXP,JSON.stringify(serialize(game))]]);
 await import('../src/main.js?events');
 const board=element('board'),tap=()=>{board.handlers.get('pointerdown')(pointer(291,478));board.handlers.get('pointerup')(pointer(291,478));element('confirm').onclick();};
 tap();assert.equal(element('discovery').hidden,false);assert.ok(element('discovery').textContent.includes('물고기'));
 const [id,callback]=timers.entries().next().value;timers.delete(id);callback();
 assert.ok(element('discovery').textContent.includes('새싹'));
 element('undo').onclick();assert.equal(element('discovery').hidden,true);assert.equal(timers.size,0);
 tap();assert.equal(element('discovery').hidden,true);assert.equal(timers.size,0);
 assert.equal(JSON.parse(storage.get(EXP)).ecosystem.seen.length,4);
});
